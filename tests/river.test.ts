import { RiverAuthority, RIVER, RIVER_TIMER_MS, FINAL_WINDOW_MS, validRiver } from '../src/river';
import type { Pose, Seat } from '../src/network';
const check = (ok: unknown, note: string): void => { if (!ok) throw new Error('FALHA: ' + note); };
const poses: Pose[] = ([0,1,2] as Seat[]).map(seat => ({ seat, x: 120 + seat * 40, y: 595, vx: 0, vy: 0 }));
const auth = new RiverAuthority();
let n = 0;
function test(ok: unknown, message: string): void { check(ok, message); n++; }
const unlocked = [true,true,true];
poses[0] = { ...poses[0], ...RIVER.lever };
test(!auth.hasWon(poses), 'fase não começa vencida');
test(!auth.act(0,{kind:'lever'},poses,[false,true,true],10000),'requer habilidade desbloqueada');
test(!auth.act(1,{kind:'lever'},poses,unlocked,10000),'outro personagem não ativa Téo');
test(auth.act(0,{kind:'lever'},poses,unlocked,10000),'alavanca de Téo');
test(auth.world.moved && auth.world.moveAt===10650,'ilusão marcada deterministicamente pelo host');
test(!auth.act(0,{kind:'lever'},poses,unlocked,10010),'idempotência da alavanca');
poses[1] = { ...poses[1], x: 300, y: 595 };
test(!auth.act(0,{kind:'shoot',facing:1},poses,unlocked,11000),'somente Lia dispara');
test(!auth.act(1,{kind:'shoot',facing:-1},poses,unlocked,11000),'direção validada');
test(auth.act(1,{kind:'shoot',facing:1},poses,unlocked,12000),'Lia libera segmento');
test(!auth.hasWon(poses),'não vence com duas peças');
poses[2] = { ...poses[2], x: RIVER.timer.x, y: RIVER.timer.y };
test(auth.act(2,{kind:'timer'},poses,unlocked,12500),'Nino abre janela');
test(auth.world.timerUntil === 12500+RIVER_TIMER_MS,'janela correta');
poses[2].x = RIVER.switch.x; poses[2].y = RIVER.switch.y;
test(!auth.act(2,{kind:'switch'},poses,unlocked,12700),'sem dash não libera');
poses[2].x = RIVER.timer.x; poses[2].y = RIVER.timer.y;
test(!auth.act(1,{kind:'dash'},poses,unlocked,12720),'Lia não usa dash');
test(!auth.act(2,{kind:'dash',facing:1},poses,unlocked,12900),'dash registrado sem alterar ponte');
poses[2].x=RIVER.switch.x; poses[2].y=RIVER.switch.y;
test(auth.act(2,{kind:'switch'},poses,unlocked,13200),'dash libera terceira peça');
test(!auth.hasWon(poses),'três peças não bastam sem cooperação final');
poses[0].x=RIVER.plate.x; poses[0].y=RIVER.plate.y;
test(auth.tick(poses,13500) && auth.world.pressure,'Téo mantém pressão');
poses[1].x=945; poses[1].y=590;
test(auth.act(1,{kind:'shoot',facing:1},poses,unlocked,14000),'Lia arma janela final');
test(auth.world.shotUntil===14000+FINAL_WINDOW_MS,'janela conjunta correta');
poses[2].x=950; poses[2].y=595;
test(!auth.act(2,{kind:'dash',facing:1},poses,unlocked,15000),'dash final registrado');
poses[2].x=RIVER.finalSwitch.x; poses[2].y=RIVER.finalSwitch.y;
test(auth.act(2,{kind:'switch'},poses,unlocked,15200),'Nino encerra cooperação');
test(auth.world.finalGate,'portão final permanente');
test(!auth.act(2,{kind:'switch'},poses,unlocked,15300),'não reabre portão');
test(!auth.hasWon(poses),'todos precisam chegar juntos');
for (const p of poses) {p.x=1178;p.y=595;}
test(auth.hasWon(poses),'três juntos vencem');
test(validRiver(auth.world),'mundo enviado é tipado e válido');
auth.reset();
test(!auth.world.partA && !auth.world.partB && !auth.world.partC,'reset correto');
test(!auth.hasWon(poses),'reset restaura regras');
const expired = new RiverAuthority();
expired.world.partA = true; expired.world.partB = true;
poses[2].x=RIVER.timer.x; poses[2].y=RIVER.timer.y;
test(expired.act(2,{kind:'timer'},poses,unlocked,18000),'janela alternativa inicia');
test(expired.tick(poses,18000+RIVER_TIMER_MS+1),'janela encerra no anfitrião');
test(expired.world.timerUntil===0,'tempo realmente zerado');
console.log('APROVADO: ' + n + ' verificações de lógica do rio.');
