import { ChapterAuthority, EYES, TRAIL, LATE_SPAWNS, movingTarget, validChapter, validJaguar } from '../src/chapters';
import { nextPlayableLevel } from '../src/levels';
import type { Pose, Seat } from '../src/network';
const unlock=[true,true,true];
let checks=0;
function check(ok:unknown,message:string):void{if(!ok)throw new Error('FALHA: '+message);checks++;}
function poses():Pose[]{return LATE_SPAWNS.map(x=>({...x}));}
const players=poses(), eyes=new ChapterAuthority(3);
check(nextPlayableLevel(1)===2 && nextPlayableLevel(2)===3 && nextPlayableLevel(3)===4,'progresso 1→2→3→4');
check(nextPlayableLevel(4)===null,'fase 05 reservada');
let at=10000;
check(validChapter(eyes.world) && eyes.world.level===3,'snapshot capítulo 3 válido');
check(!eyes.hasWon(players),'vitória 3 inicialmente bloqueada');
players[0].x=EYES.lever.x;players[0].y=EYES.lever.y;
check(!eyes.act(1,{kind:'lever'},players,unlock,at),'outro jogador não usa Téo');
check(!eyes.act(0,{kind:'lever'},players,[false,true,true],at),'desbloqueio obrigatório');
check(eyes.act(0,{kind:'lever'},players,unlock,at),'Téo libera raízes');
check(!eyes.act(0,{kind:'lever'},players,unlock,at+20),'idempotência alavanca');
players[1].x=430;players[1].y=590;
check(!eyes.act(0,{kind:'shoot',facing:1},players,unlock,at+100),'somente Lia dispara');
check(!eyes.act(1,{kind:'shoot',facing:-1},players,unlock,at+100),'Lia deve olhar para alvo');
check(eyes.act(1,{kind:'shoot',facing:1},players,unlock,at+200),'Lia distrai onça');
check(eyes.world.level===3 && eyes.world.distractedUntil===at+200+6700,'janela da distração tolera latência');
const res=eyes.tick(players,at+260);
check(res.hits.length===0 && eyes.jaguar.mode==='distracted','onça distraída não ataca');
players[2].x=EYES.timer.x;players[2].y=EYES.timer.y;
check(eyes.act(2,{kind:'timer'},players,unlock,at+400),'Nino aciona temporizador');
players[2].x=708;players[2].y=598;
check(!eyes.act(2,{kind:'dash',facing:1},players,unlock,at+450),'dash registra movimento');
players[2].x=EYES.switch.x;players[2].y=EYES.switch.y;
check(eyes.act(2,{kind:'switch'},players,unlock,at+1100),'Nino destrava corredor com dash');
check(!eyes.hasWon(players),'mecanismos 3 não completados');
players[0].x=EYES.plate.x;players[0].y=EYES.plate.y;
check(eyes.tick(players,at+1200).changed && eyes.world.level===3 && eyes.world.pressure,'placa segurada por Téo');
players[1].x=820;players[1].y=590;
check(eyes.act(1,{kind:'shoot',facing:1},players,unlock,at+2000),'Lia atinge alvo final');
players[2].x=925;players[2].y=595;
check(!eyes.act(2,{kind:'dash',facing:1},players,unlock,at+2400),'dash final registrado');
players[2].x=EYES.finalSwitch.x;players[2].y=EYES.finalSwitch.y;
check(eyes.act(2,{kind:'switch'},players,unlock,at+2800),'Nino abre saída final');
check(eyes.world.finalGate && !eyes.hasWon(players),'saída 3 exige todos juntos');
for(const p of players){p.x=1170;p.y=594;}
check(eyes.hasWon(players),'vitória capítulo 3 com os três');
eyes.reset(3);
check(eyes.world.level===3 && !eyes.hasWon(players),'reset do 3 preserva regras');
const chasing=new ChapterAuthority(3), chasePos=poses();
chasePos[1].x=595;chasePos[1].y=594;
const hit=chasing.tick(chasePos,20000);
check(hit.hits.includes(1),'onça detecta colisão');
check(validJaguar(chasing.jaguar) && chasing.jaguar.mode==='chase','onça é autoritativa e válida');
check(chasing.jaguar.platformX>=752 && chasing.jaguar.platformX<=858,'plataforma sincronizada pelo anfitrião');
check(!chasing.tick(chasePos,20050).hits.includes(1),'invulnerabilidade temporária');
chasePos[1].x=200;
check(chasing.tick(chasePos,20400).hits.length===0,'onça sem jogador próximo volta a patrulhar');

const trail=new ChapterAuthority(4), group=poses();
check(validChapter(trail.world)&&trail.world.level===4,'snapshot capítulo 4 válido');
check(!trail.hasWon(group),'vitória 4 bloqueada');
group[2].x=TRAIL.star.x;group[2].y=TRAIL.star.y;
check(trail.act(2,{kind:'switch'},group,unlock,30000),'totem fora de ordem sinaliza falha');
check(trail.world.level===4 && trail.world.errors===1 && trail.world.totems===0,'erro reinicia só a sequência');
group[0].x=TRAIL.moon.x;group[0].y=TRAIL.moon.y;
check(trail.act(0,{kind:'lever'},group,unlock,30200),'Téo ativa lua');
check(trail.world.level===4 && trail.world.totems===1 && trail.world.signsChanged,'placas mudam no host');
group[1].x=500;group[1].y=590;
check(trail.act(1,{kind:'shoot',facing:1},group,unlock,31000),'Lia ativa folha');
group[2].x=705;group[2].y=591;
check(!trail.act(2,{kind:'dash',facing:1},group,unlock,31300),'dash Nino para estrela registrado');
group[2].x=TRAIL.star.x;group[2].y=TRAIL.star.y;
check(trail.act(2,{kind:'switch'},group,unlock,31900),'Nino ativa estrela na ordem');
check(trail.world.level===4 && trail.world.totems===3 && trail.world.transformed,'transformação sincronizável');
check(trail.tick(group,34100).changed && trail.world.level===4 && !trail.world.platformsOn,'plataformas desaparecem por evento');
check(trail.tick(group,36200).changed && trail.world.level===4 && trail.world.platformsOn,'plataformas reaparecem');
group[0].x=TRAIL.plate.x;group[0].y=TRAIL.plate.y;
check(trail.tick(group,36400).changed && trail.world.level===4 && trail.world.pressure,'Téo permanece na placa');
const target=movingTarget(37000);
check(target.x>=TRAIL.movingTargetMin && target.x<=TRAIL.movingTargetMax,'alvo móvel determinístico');
group[1].x=850;group[1].y=590;
check(trail.act(1,{kind:'shoot',facing:1},group,unlock,37000),'Lia acerta alvo móvel');
group[2].x=935;group[2].y=595;
check(!trail.act(2,{kind:'dash',facing:1},group,unlock,37500),'Nino usa dash final');
group[2].x=TRAIL.finalSwitch.x;group[2].y=TRAIL.finalSwitch.y;
check(trail.act(2,{kind:'switch'},group,unlock,38300),'Nino abre passagem final');
check(trail.world.level===4 && trail.world.finalGate && trail.world.platformsOn,'saída permanente e plataformas seguras');
check(!trail.hasWon(group),'não encerra sem trio');
for(const p of group){p.x=1168;p.y=595;}
check(trail.hasWon(group),'todos concluem capítulo 4 juntos');
trail.reset(4);
check(trail.world.level===4 && !trail.hasWon(group),'reset da fase 4');

console.log('APROVADO: '+checks+' verificações das Fases 03 e 04.');
