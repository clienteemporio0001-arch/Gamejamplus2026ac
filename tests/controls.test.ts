import { GameKeys, actionFromKey } from '../src/keyboard';

let tests=0;
function assert(ok: unknown, reason: string): void {
  if(!ok) throw new Error('FALHA: '+reason);
  tests++;
}
const g=new GameKeys();
assert(actionFromKey('Space')==='jump','Espaço é pulo');
assert(actionFromKey('ArrowUp')==='jump','seta para cima é pulo');
assert(actionFromKey('ShiftLeft')==='dash','Shift esquerdo é dash');
assert(actionFromKey('ShiftRight')==='dash','Shift direito é dash');
assert(actionFromKey('KeyJ')==='slingshot','J é baladeira');
assert(actionFromKey('KeyQ')===null,'Q não é mais habilidade');
assert(actionFromKey('KeyW')===null,'W não é pulo');
assert(!g.keyDown('Space'),'teclado desligado não intercepta pulo no lobby');
g.setEnabled(true);
assert(g.keyDown('Space')&&g.consumeJump(),'Espaço gera pulo');
assert(!g.consumeJump(),'um toque de Espaço não gera dois pulos');
assert(g.keyDown('Space',true)&&!g.consumeJump(),'repetição automática não gera salto duplo');
g.keyUp('Space');
assert(g.keyDown('Space')&&g.consumeJump(),'soltar e pressionar Espaço permite segundo salto');
g.keyUp('Space');
assert(g.keyDown('ArrowUp')&&g.consumeJump(),'seta para cima volta a pular');
g.keyUp('ArrowUp');
g.keyDown('ShiftLeft');
assert(g.consumeSkill(2),'Shift ativa dash do Nino');
assert(!g.consumeSkill(2),'manter Shift não repete dash');
g.keyUp('ShiftLeft');
g.keyDown('ShiftRight');
assert(g.consumeSkill(2),'Shift direito também ativa dash');
g.keyUp('ShiftRight');
g.keyDown('KeyJ');
assert(g.consumeSkill(1),'J dispara baladeira da Lia');
assert(!g.consumeSkill(2),'J não ativa dash');
g.keyUp('KeyJ');
g.keyDown('KeyQ');
assert(!g.consumeSkill(1)&&!g.consumeSkill(2),'Q não ativa mais habilidade');
g.keyUp('KeyQ');
g.keyDown('ShiftLeft');
assert(!g.consumeSkill(1),'Lia não usa Shift');
g.keyUp('ShiftLeft');
g.keyDown('KeyJ');
assert(!g.consumeSkill(0),'Téo não usa baladeira');
g.setEnabled(false);
assert(!g.consumeSkill(1),'teclas pendentes limpas durante introdução/pausa');
assert(!g.keyDown('Space'),'teclado não intercepta botões de menu');
g.setEnabled(true);
assert(!g.consumeJump()&&!g.consumeSkill(1),'retorno ao jogo sem comandos fantasmas');
g.keyDown('Space');
g.clear();
assert(!g.consumeJump(),'perda de foco limpa tecla pendente');
console.log('APROVADO: '+tests+' testes de controle Espaço/↑/Shift/J e prevenção de repetição.');
