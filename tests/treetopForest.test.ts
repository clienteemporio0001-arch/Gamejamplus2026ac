import {strict as assert} from 'node:assert';
import {TREE_PLATFORMS,TREE_START,TREE_CYCLE,TREE_VOID_Y,TreeAuthority,initTree,treeFatal,treeObjective,treePlatforms} from '../src/treetopForest';
const at=100000;
const a=new TreeAuthority();a.reset(at);
assert.equal(TREE_START.length,3);
assert.equal(TREE_PLATFORMS.some(p=>p.width>700),false,'No continuous floor');
assert.equal(treeFatal({...TREE_START[0],y:TREE_VOID_Y+20,vy:120},at,a.world),true);
assert.equal(treeFatal({...TREE_START[0],y:TREE_VOID_Y+20,vy:-120},at,a.world),false);
assert.equal(a.tick(TREE_START,at+TREE_CYCLE).changed,true);
assert.equal(a.world.blackoutUntil>0,true);
assert.equal(a.tick(TREE_START,at+TREE_CYCLE+2100).changed,true);
assert.equal(a.world.layout,1);
assert.equal(a.world.cycle,1);
const poses=TREE_START.map(p=>({...p}));
poses[0].y=TREE_VOID_Y+10;poses[0].vy=200;
a.tick(poses,at+TREE_CYCLE+3000);
assert.equal(a.world.health[0],0);
const outcome=a.tick(poses,at+TREE_CYCLE+5000);
assert.equal(outcome.reset,true);
assert.deepEqual(a.world.health,[3,3,3]);
assert.equal(a.world.layout,0);
assert.equal(treePlatforms(initTree()).some(p=>p.puzzle==='bridge'),false);
assert.equal(treeObjective(initTree()).progress,'0/3');
console.log('Treetop core assertions passed');
