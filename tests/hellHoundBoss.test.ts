import {strict as assert} from 'node:assert';
import {readFileSync} from 'node:fs';
import {initFire,FireAuthority,FIRE_START,validFire,fireDamageZone,FIRE_CLEARING_LEFT} from '../src/burningForest';
import {HOUND_HP,HOUND_LEFT,HOUND_HOME,initHound,validHound,tickHound,armHound,shootHound} from '../src/hellHoundBoss';
import type {Pose} from '../src/network';
const at=100000;
const stage=initFire(at);
assert.equal(stage.hound.hp,HOUND_HP);
assert.equal(validHound(stage.hound),true);
assert.ok(validFire(stage));
const p=(seat:0|1|2,x:number,y=651,vx=0,vy=0):Pose=>({seat,x,y,vx,vy});
const h=stage.hound;
stage.treeOpen=true;
assert.ok(h.x===HOUND_HOME);
assert.ok(tickHound(stage,[p(0,4650)],at+100));
assert.equal(h.active,true,'player crossing the boss sign awakens the Hound');
assert.ok(h.x>=HOUND_LEFT,'Boss never goes left of its pursuit sign');
h.nextLeapAt=at+50000;h.leapAt=0;h.y=651;h.x=HOUND_HOME;
armHound(stage,0,'doubleJump',at+200,1);
tickHound(stage,[p(0,HOUND_HOME,585,0,260)],at+300);
assert.equal(h.hp,HOUND_HP-2,'Teo double jump damages the guardian');
assert.equal(stage.health[0],3,'correct stomp cannot hurt Teo on the same hit');
assert.ok(stage.ratImpacts[0]?.vy!<0,'Teo receives a recoil');
armHound(stage,2,'dash',at+900,1);
tickHound(stage,[p(2,HOUND_HOME-15,651,285,0)],at+950);
assert.equal(h.hp,HOUND_HP-4,'Nino dash damages the guardian');
assert.equal(stage.health[2],3,'successful dash is protected');
assert.ok(stage.ratImpacts[2]?.vx!<0,'Dash bounces Nino backward');
assert.ok(shootHound(stage,p(1,HOUND_HOME-270,651),1,at+1450),'Lia slingshot damages guardian');
assert.equal(h.hp,HOUND_HP-5);
for(let n=0;n<60;n++)tickHound(stage,[p(0,HOUND_LEFT-80)],at+2000+n*70);
assert.equal(h.x,HOUND_HOME,'guardian walks back to home if all players retreat');
assert.equal(h.active,false,'guardian resets pursuit when back at home');
assert.equal(h.hp,HOUND_HP-5,'retreat does not heal guardian');
const ordinary=initFire(at);
ordinary.treeOpen=true;
for(const x of [4390,4520,4750,5010])
 assert.equal(fireDamageZone(ordinary,{x,y:651},at+11000),false,'final arena stays free of flames');
const fight=new FireAuthority();
fight.world.logOpen=true;fight.world.smokeOpen=true;fight.world.treeOpen=true;
const finish=FIRE_START.map(q=>({...q,x:5020,y:648}));
const result=fight.tick(finish,at+80,at+2000);
assert.notEqual(result.won,true,'final boss blocks the ending');
fight.world.hound.hp=0;fight.world.hound.defeatedAt=at+500;
assert.equal(fight.tick(finish,at+100,at+2000).won,true,'defeated boss unlocks ending');
const falling=new FireAuthority();falling.reset(at);
const fallPose=FIRE_START.map(q=>({...q}));fallPose[1].y=820;
assert.equal(falling.tick(fallPose,at+300).respawn,true,'falls still reset the whole party');
assert.equal(falling.world.hound.hp,HOUND_HP,'full reset restores the guardian');
const visual=readFileSync('src/hellHoundVisual.ts','utf8');
assert.ok(visual.includes('scene.load.image(KEY'), 'boss image uses one static frame');
assert.ok(visual.includes('hellhound-static-rgba.png?v=3'), 'cache busts old indexed PNG');
assert.ok(visual.includes('.setScale(2)'), 'boss remains exactly double size');
assert.ok(!visual.includes('load.spritesheet'), 'no animated indexed sheet can render a black rectangle');
assert.ok(!visual.includes('.setFrame('), 'no invalid animation frame or cropping');
assert.ok(visual.includes('textureReady'), 'graphics-only fallback if image fails to load');
const png=readFileSync('public/assets/enemies/hellhound-static-rgba.png');
assert.equal(png.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
assert.equal(png.readUInt32BE(16),72);
assert.equal(png.readUInt32BE(20),48);
assert.equal(png[25],6,'boss texture is 32-bit truecolor with alpha, never palette index');
console.log('Final boss: RGBA static sprite, 2x size, no black background, combat and fall reset OK');
